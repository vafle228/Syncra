import type { SyncStatus } from '../contract'

/**
 * Синхронизация в фейк-ядре (F10).
 *
 * Настоящей сети здесь нет и не будет: discovery, TCP и обмен диффом (§5.1,
 * §5.3, §5.6) живут в Rust. Фейк-ядро изображает только то, что видно UI, —
 * смену фаз, счётчики и время последнего обмена, — чтобы индикатор можно было
 * проверить, не поднимая второго устройства.
 */

/** Статус, с которого начинается хранилище: обмена ещё не было ни разу. */
export function initialSyncStatus(): SyncStatus {
  return {
    phase: 'idle',
    peers_online: 0,
    peer_name: null,
    pending_records: [],
    last_sync_at: null,
    message: null,
  }
}

/**
 * Шаг демо-цикла: найти пира → обменяться → успокоиться. Пять секунд — чтобы
 * состояния успевали читаться глазами, но экран не выглядел зависшим.
 */
export const SYNC_SIMULATION_STEP_MS = 5_000

/**
 * Что показывается в фазе `error`.
 *
 * Формулировка из макета: обрыв — это «данные целы, не доехала последняя порция»,
 * а не потеря. Красный в Syncra оставлен для настоящей потери данных.
 */
export const SYNC_FAILURE_MESSAGE = 'Соединение оборвалось. Данные целы — не доехал только дифф.'
